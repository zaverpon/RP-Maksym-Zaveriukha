int main()
{
  printf("Enter number of proccesses \n");
  int rank = 0;
  int nr_proc = 0;
  scanf("%d" ,&nr_proc);

  com_initialize(nr_proc, &rank);

  if (rank == 0){
    sleep(nr_proc);
  } else {
    sleep(rank);
  }

  printf("Process finishing: rank=%d, pid=%d\n", rank, getpid());

  com_finalize();
  return 0; /* required */
}
